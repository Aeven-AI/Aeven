/**
 * Vendor the upstream aitmpl skill catalog into this repository.
 *
 * This script runs when preparing a release, never inside a running deployment: the generated
 * catalog travels inside the package and the Host reads it from disk. One invocation pins an
 * upstream commit, downloads every skill directory under `cli-tool/components/skills`, stores one
 * zip per skill, and writes the catalog index the Host serves.
 *
 * Usage: pnpm exec tsx scripts/sync-skill-catalog.ts [--ref <git-ref>] [--out <dir>]
 *
 * Installed names come from the upstream directory name, which is the kebab-case identity Aeven
 * requires; a name two categories both claim is prefixed with its category, so one install cannot
 * shadow the other. The vendored `SKILL.md` frontmatter carries the same name, so an imported
 * bundle and the index agree. Skill directories nested inside another skill directory are vendored
 * as their own entries and excluded from the parent's bundle.
 *
 * `catalog/curation.json` carries a reviewed value judgement per skill, copied into the index as
 * `verdict` and `value`; it is regenerated by review, not by this script, and a skill it does not
 * mention simply arrives without those fields.
 *
 * Requires the `zip` command-line tool and network access.
 */

import { createHash } from 'node:crypto'
import { execFileSync } from 'node:child_process'
import { existsSync, globSync, mkdirSync, mkdtempSync, readFileSync, rmSync, utimesSync, writeFileSync } from 'node:fs'
import { tmpdir } from 'node:os'
import { dirname, join, relative, resolve, sep } from 'node:path'

const UPSTREAM = 'davila7/claude-code-templates'
const SKILLS_PREFIX = 'cli-tool/components/skills/'
const DEFAULT_OUT = 'packages/skill/skill-catalog/catalog'
const DOWNLOAD_CONCURRENCY = 16
/** Every zip entry and directory carries this timestamp, so re-syncing unchanged content gives the same bytes. */
const FIXED_MTIME_SECONDS = 315_532_800

interface TreeEntry {
  readonly path: string
  readonly type: string
}

interface UpstreamComponent {
  readonly path: string
  readonly description?: string
  readonly keywords?: string[]
  readonly downloads?: number
  readonly author?: string
}

/** One vendored catalog entry, as the Host serves it and the gate checks it. */
interface CatalogEntry {
  /** Name the skill installs under; kebab-case and unique across the catalog. */
  readonly name: string
  /** Upstream `SKILL.md` name, kept for display because some upstream names are not kebab-case. */
  readonly displayName: string
  readonly category: string
  readonly description: string
  readonly keywords: readonly string[]
  readonly downloads: number
  readonly author: string
  /** Upstream path relative to `cli-tool/components/skills`. */
  readonly path: string
  readonly files: number
  readonly bytes: number
  /** SHA-256 of the vendored zip, which is what an install unpacks. */
  readonly sha256: string
  /** Reviewed judgement against the harness native surface, absent until curation covers the skill. */
  readonly verdict?: string
  /** Reviewed value 1-5; Settings shows the recommended set by default. */
  readonly value?: number
}

/** The catalog index the Host serves and `verify-skill-catalog` re-derives. */
interface CatalogIndex {
  readonly upstream: { readonly repo: string; readonly commit: string; readonly synced: string }
  readonly categories: readonly { readonly name: string; readonly skills: number }[]
  readonly skills: readonly CatalogEntry[]
}

/** Complete parsed options for one sync run. */
interface Options {
  readonly ref: string
  readonly out: string
}

/**
 * Read the sync options.
 * @param argv - process arguments after the script name.
 * @returns the upstream ref to pin and the output directory.
 */
function options(argv: readonly string[]): Options {
  const value = (flag: string): string | undefined => {
    const index = argv.indexOf(flag)
    return index === -1 ? undefined : argv[index + 1]
  }
  return { ref: value('--ref') ?? 'main', out: value('--out') ?? DEFAULT_OUT }
}

/**
 * Fetch JSON from an absolute URL.
 * @param url - the URL to read.
 * @returns the parsed JSON value.
 */
async function json<T>(url: string): Promise<T> {
  const response = await fetch(url, { headers: { accept: 'application/vnd.github+json' } })
  if (!response.ok) throw new Error(`${url} returned ${response.status}`)
  return await response.json() as T
}

/**
 * Derive the kebab-case name Aeven accepts from an upstream directory name.
 * @param raw - the upstream directory name.
 * @returns a lowercase hyphenated name.
 */
function kebab(raw: string): string {
  const name = raw.toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '')
  if (!/^[a-z0-9]+(?:-[a-z0-9]+)*$/.test(name)) throw new Error(`cannot derive a skill name from ${JSON.stringify(raw)}`)
  return name
}

/**
 * Read one `SKILL.md` frontmatter field.
 * @param markdown - the file contents.
 * @param field - the frontmatter key to read.
 * @returns the value, or undefined when the block declares none.
 */
function frontmatterField(markdown: string, field: string): string | undefined {
  const block = /^---\r?\n([\s\S]*?)\r?\n---/.exec(markdown)
  const match = block?.[1] === undefined ? null : new RegExp(`^${field}:\\s*(.*)$`, 'm').exec(block[1])
  const value = match?.[1]?.trim().replace(/^["']|["']$/g, '')
  if (value === undefined || value === '') return undefined
  // A block scalar keeps its text on the lines below the marker; the marker alone is not the value.
  if (/^[|>][-+]?$/.test(value)) {
    const following = block?.[1]?.slice(block[1].indexOf(match![0]) + match![0].length).split('\n') ?? []
    return following.map(line => line.trim()).find(line => line !== '')
  }
  return value
}

/**
 * Rewrite the `name:` field of one `SKILL.md` frontmatter block.
 * @param markdown - the upstream file contents.
 * @param name - the name the vendored bundle installs under.
 * @returns the contents with the frontmatter name replaced.
 */
function renameFrontmatter(markdown: string, name: string): string {
  const block = /^---\r?\n([\s\S]*?)\r?\n---/.exec(markdown)
  if (block?.[1] === undefined) throw new Error('vendored SKILL.md has no frontmatter')
  return markdown.replace(block[1], block[1].replace(/^name:.*$/m, `name: ${name}`))
}

/**
 * Rewrites that read upstream's own harness, product, model, and directory names as Aeven's. Ordered:
 * the specific names go first, and the last rule is the sweep that leaves no other mention of that
 * vendor behind. Model identifiers become Aeven's own models, which is what the catalog names.
 */
const REBRAND_RULES: readonly { readonly pattern: RegExp; readonly replacement: string }[] = [
  { pattern: /anthropic\/claude-opus[-.\d]*/g, replacement: 'Aeven-1.0-Pro' },
  { pattern: /anthropic\/claude-sonnet[-.\d]*/g, replacement: 'Aeven-1.0-Flash' },
  { pattern: /\bclaude-opus[-.\d]*/g, replacement: 'Aeven-1.0-Pro' },
  { pattern: /\bclaude-sonnet[-.\d]*/g, replacement: 'Aeven-1.0-Flash' },
  // The article travels with the name it introduces: "A Claude Code skill" becomes "An Aeven skill".
  { pattern: /\bA Claude Code\b/g, replacement: 'An Aeven' },
  { pattern: /Claude Code/gi, replacement: 'Aeven' },
  // A vendored bundle installs under .aeven, and this repository's own config names carry the same word.
  { pattern: /\.claude\//g, replacement: '.aeven/' },
  { pattern: /CLAUDE\.md/g, replacement: 'AEVEN.md' },
  { pattern: /CLAUDE_PLUGIN_ROOT/g, replacement: 'AEVEN_PLUGIN_ROOT' },
  { pattern: /claude-scientific-writer/g, replacement: 'aeven-scientific-writer' },
  // Private identifiers of a vendored script, renamed with the author string the same file compares
  // against, so the validator still recognizes the revisions this harness authors.
  { pattern: /claude_del_elements/g, replacement: 'aeven_del_elements' },
  { pattern: /claude_ins_elements/g, replacement: 'aeven_ins_elements' },
  { pattern: /_remove_claude_tracked_changes/g, replacement: '_remove_aeven_tracked_changes' },
  { pattern: /Claude/gi, replacement: 'Aeven' },
]

/**
 * Read one vendored text file as Aeven's own writing.
 * @param text - the file contents as upstream serves them.
 * @returns the contents with every rewrite applied.
 */
function rebrand(text: string): string {
  let rebranded = text
  for (const rule of REBRAND_RULES) rebranded = rebranded.replace(rule.pattern, rule.replacement)
  return rebranded
}

/**
 * Rewrite one downloaded file in place of upstream's wording.
 * @param bytes - the file as upstream serves it.
 * @returns the bytes to stage, which are upstream's own when the file carries no text to read.
 */
function rebrandBytes(bytes: Buffer): Buffer {
  let text: string
  try {
    text = new TextDecoder('utf-8', { fatal: true }).decode(bytes)
  } catch {
    // A file that is not UTF-8 text — an image, a font, an archive — carries no copy to rewrite.
    return bytes
  }
  const rebranded = rebrand(text)
  return rebranded === text ? bytes : Buffer.from(rebranded, 'utf8')
}

/**
 * Create a directory together with its ancestors, stamping each directory this call creates.
 * @param path - the directory to create.
 */
function makeDirectory(path: string): void {
  const missing: string[] = []
  for (let current = path; !existsSync(current); current = dirname(current)) {
    missing.push(current)
    if (current === dirname(current)) break
  }
  for (const directory of missing.reverse()) {
    mkdirSync(directory, { recursive: true })
    utimesSync(directory, FIXED_MTIME_SECONDS, FIXED_MTIME_SECONDS)
  }
}

/**
 * Run one task per item with a bounded number in flight.
 * @param items - the work items.
 * @param limit - how many tasks may run at once.
 * @param task - the work to run for one item.
 */
async function pool<T>(items: readonly T[], limit: number, task: (item: T) => Promise<void>): Promise<void> {
  let next = 0
  const workers = Array.from({ length: Math.min(limit, items.length) }, async () => {
    while (next < items.length) await task(items[next++]!)
  })
  await Promise.all(workers)
}

/**
 * Sync the catalog.
 */
async function main(): Promise<void> {
  const { ref, out } = options(process.argv.slice(2))
  const outDir = resolve(out)
  const commit = (await json<{ sha: string }>(`https://api.github.com/repos/${UPSTREAM}/commits/${ref}`)).sha
  const tree = await json<{ tree: readonly TreeEntry[] }>(`https://api.github.com/repos/${UPSTREAM}/git/trees/${commit}?recursive=1`)
  const components = await json<{ skills?: readonly UpstreamComponent[] }>(`https://raw.githubusercontent.com/${UPSTREAM}/${commit}/docs/components.json`)
  const metadata = new Map((components.skills ?? []).map(component => [component.path, component]))
  const curationFile = join(outDir, '..', 'curation.json')
  const reviewed = existsSync(curationFile)
    ? JSON.parse(readFileSync(curationFile, 'utf8')) as { minValue?: number; skills?: Record<string, { verdict?: string; value?: number }> }
    : {}
  const curation = new Map<string, { verdict?: string; value?: number }>(Object.entries(reviewed.skills ?? {}))
  const minValue = reviewed.minValue ?? 0
  const blobs = tree.tree.filter(entry => entry.type === 'blob' && entry.path.startsWith(SKILLS_PREFIX))
  const roots = blobs.filter(entry => entry.path.endsWith('/SKILL.md'))
    .map(entry => entry.path.slice(0, -'/SKILL.md'.length))
  const claims = new Map<string, number>()
  const relativeOf = (root: string): string => root.slice(SKILLS_PREFIX.length)
  const baseOf = (root: string): string => kebab(relativeOf(root).split('/').at(-1)!)
  for (const root of roots) claims.set(baseOf(root), (claims.get(baseOf(root)) ?? 0) + 1)
  // A basename two skills claim is prefixed with its category; when one category holds both, the
  // whole upstream path disambiguates them.
  const names = new Map<string, string>()
  const taken = new Set<string>()
  for (const root of [...roots].sort()) {
    const base = baseOf(root)
    const segments = relativeOf(root).split('/')
    const candidates = (claims.get(base) ?? 0) > 1
      ? [`${kebab(segments[0]!)}-${base}`, segments.map(kebab).join('-')]
      : [base]
    const name = candidates.find(candidate => !taken.has(candidate)) ?? candidates[candidates.length - 1]!
    taken.add(name)
    names.set(root, name)
  }
  console.log(`sync-skill-catalog: ${commit.slice(0, 12)}, ${roots.length} skills in ${blobs.length} files`)

  /** Files of one skill directory, excluding every skill directory nested inside it. */
  const filesOf = (root: string): readonly TreeEntry[] => blobs.filter(entry => entry.path.startsWith(`${root}/`)
    && !roots.some(other => other.startsWith(`${root}/`) && entry.path.startsWith(`${other}/`)))

  const scratch = mkdtempSync(join(tmpdir(), 'skill-catalog-'))
  const entries: CatalogEntry[] = []
  // Every skill stages into its own directory, so a parent's bundle cannot pick up the files its
  // nested skills were downloaded into.
  // The catalog ships the reviewed set only: every other judged skill stays in curation.json, so
  // raising or lowering one number in that file is what widens or narrows what a release vendors.
  const shipped = roots.filter(root => (curation.get(names.get(root)!)?.value ?? 0) >= minValue)
  console.log(`sync-skill-catalog: vendoring ${shipped.length} of ${roots.length} skills at value >= ${minValue}`)
  const staged = shipped.map((root, position) => ({ root, position, directory: join(scratch, String(position)), files: filesOf(root) }))
  try {
    const downloads = staged.flatMap(skill => skill.files.map(entry => ({ skill, entry })))
    let fetched = 0
    await pool(downloads, DOWNLOAD_CONCURRENCY, async ({ skill, entry }) => {
      const target = join(skill.directory, relative(skill.root, entry.path))
      makeDirectory(dirname(target))
      const response = await fetch(`https://raw.githubusercontent.com/${UPSTREAM}/${commit}/${entry.path}`)
      if (!response.ok) throw new Error(`${entry.path} returned ${response.status}`)
      writeFileSync(target, rebrandBytes(Buffer.from(await response.arrayBuffer())))
      utimesSync(target, FIXED_MTIME_SECONDS, FIXED_MTIME_SECONDS)
      fetched += 1
      if (fetched % 500 === 0) console.log(`sync-skill-catalog: ${fetched}/${downloads.length} files downloaded`)
    })

    for (const skill of staged) {
      const relativeRoot = skill.root.slice(SKILLS_PREFIX.length)
      const category = relativeRoot.split('/')[0]!
      const definition = join(skill.directory, 'SKILL.md')
      const upstream = readFileSync(definition, 'utf8')
      const name = names.get(skill.root)!
      writeFileSync(definition, renameFrontmatter(upstream, name))
      utimesSync(definition, FIXED_MTIME_SECONDS, FIXED_MTIME_SECONDS)
      const target = join(outDir, 'bundles', category, `${name}.zip`)
      makeDirectory(dirname(target))
      // An explicit, sorted file list keeps the archive bytes independent of directory enumeration order.
      const members = skill.files.map(entry => relative(skill.root, entry.path)).sort()
      execFileSync('zip', ['-X', '-q', target, ...members], { cwd: skill.directory })
      const bytes = readFileSync(target)
      const component = metadata.get(relativeRoot)
      entries.push({
        name,
        displayName: frontmatterField(upstream, 'name') ?? name,
        category,
        description: rebrand(component?.description ?? frontmatterField(upstream, 'description') ?? ''),
        keywords: component?.keywords ?? [],
        downloads: component?.downloads ?? 0,
        author: component?.author ?? '',
        path: relativeRoot,
        files: skill.files.length,
        bytes: bytes.byteLength,
        sha256: createHash('sha256').update(bytes).digest('hex'),
        ...curation.get(name) ?? {},
      })
      if ((skill.position + 1) % 50 === 0) console.log(`sync-skill-catalog: ${skill.position + 1}/${staged.length} skills bundled`)
    }
  } finally {
    rmSync(scratch, { recursive: true, force: true })
  }

  // Bundles of skills the upstream no longer ships go only now, with the index that replaces them:
  // a run that dies mid-download leaves the previous catalog complete on disk.
  const fresh = new Set(entries.map(entry => join('bundles', entry.category, `${entry.name}.zip`)))
  for (const existing of globSync('bundles/**/*.zip', { cwd: outDir })) {
    if (!fresh.has(existing.split(sep).join('/'))) rmSync(join(outDir, existing), { force: true })
  }

  entries.sort((left, right) => left.category.localeCompare(right.category) || left.name.localeCompare(right.name))
  if (new Set(entries.map(entry => entry.name)).size !== entries.length) throw new Error('vendored skill names are not unique')
  const categories = [...new Set(entries.map(entry => entry.category))].sort()
    .map(name => ({ name, skills: entries.filter(entry => entry.category === name).length }))
  const index: CatalogIndex = { upstream: { repo: UPSTREAM, commit, synced: new Date().toISOString().slice(0, 10) }, categories, skills: entries }
  mkdirSync(outDir, { recursive: true })
  writeFileSync(join(outDir, 'index.json'), `${JSON.stringify(index, null, 2)}\n`)
  writeFileSync(join(outDir, 'MANIFEST.md'), [
    '# Vendored skill catalog',
    '',
    `Upstream: ${UPSTREAM} at ${commit}`,
    `Synced: ${index.upstream.synced}`,
    `Skills: ${entries.length} in ${categories.length} categories (value >= ${minValue} of the reviewed catalog)`,
    `Reviewed but not vendored: ${curation.size - entries.length}`,
    'Rewritten: every reference to the other harness, its product, its model identifiers, and its',
    'skill directory reads as Aeven’s. The upstream repository name, and the Anthropic SDK, API key,',
    'and copyright notices inside vendored scripts, are published as upstream wrote them.',
    '',
    'Regenerate while preparing a release with `pnpm exec tsx scripts/sync-skill-catalog.ts`.',
    '',
    '| Category | Skills |',
    '| --- | --- |',
    ...categories.map(category => `| ${category.name} | ${category.skills} |`),
    '',
  ].join('\n'))
  const total = entries.reduce((sum, entry) => sum + entry.bytes, 0)
  console.log(`sync-skill-catalog: wrote ${entries.length} skills, ${(total / 1e6).toFixed(1)} MB of bundles into ${relative(process.cwd(), outDir)}`)
}

await main()
